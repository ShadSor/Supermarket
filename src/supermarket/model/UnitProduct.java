package supermarket.model;

/**
 * Класс, представляющий товар, продающийся поштучно.
 * Наследуется от {@link Product} и используется для товаров с фиксированной ценой за единицу.
 * Примеры: бутылка воды, пачка печенья и т.д.
 * Дополнительная логика не требуется — вся функциональность унаследована от базового класса.
 */
public class UnitProduct extends Product {

    /**
     * Создаёт товар, продающийся поштучно.
     *
     * @param id    уникальный идентификатор товара
     * @param name  название товара
     * @param price базовая цена за единицу товара
     */
    public UnitProduct(String id, String name, double price) {
        super(id, name, price);
    }
}